import {createRequire} from 'node:module'
const require=createRequire(import.meta.url)
const {chromium}=require('playwright-core')
const url='http://localhost:5175'
const b=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']})
const page=await b.newPage({viewport:{width:1440,height:1050}})
page.on('pageerror',e=>console.log('PAGEERROR',e.message))
await page.route('**/*',r=>new URL(r.request().url()).origin===new URL(url).origin?r.continue():r.abort())
await page.goto(url)
await page.getByRole('button',{name:'Load completed real example',exact:true}).click()
await page.getByRole('button',{name:'Walk around',exact:true}).waitFor({timeout:60000})
await page.getByRole('button',{name:/Fit & Align/}).click()
await page.getByRole('button',{name:'Adjust',exact:true}).click()
const svg=page.getByRole('img',{name:'Top-down manual placement editor'})
await svg.waitFor()
const box=await svg.boundingBox()
console.log('svg box',box)
const offsetText=async()=>{const t=await page.locator('p.dimmer').filter({hasText:'Offset'}).innerText().catch(()=>'none');return t.slice(0,60)}
console.log('before:',await offsetText())
await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
await page.mouse.down()
for(let i=1;i<=10;i++){await page.mouse.move(box.x+box.width/2+i*8,box.y+box.height/2+i*5);await page.waitForTimeout(30)}
await page.mouse.up()
await page.waitForTimeout(600)
console.log('after :',await offsetText())
await b.close()
